'use client';

import { memo } from 'react';
import type { Row } from '../geometry';

/**
 * The text column and its gutter, one fixed-height row per visual line.
 *
 * Each row is drawn from a plain description and re-rendered only when that
 * description changes, which is what keeps the canvas at frame rate while
 * tokens stream: a frame of new tokens touches the last row or two, not the
 * page.
 *
 * A token's key is its place and its text. A word that a control change
 * rewrites is therefore a new element and fades in; a word that survives the
 * change is the same element and does not move. That is what makes regenerated
 * text read as morphing rather than being replaced.
 */

export type GutterVariant = 'heat' | 'bar' | 'weight';

export interface RowView {
  index: number;
  row: Row;
  tokens: readonly string[];
  /** per token on this row: k committed, a kept, s speculative, g ghost */
  tone: string;
  /** per token: 1 if it is among the most attended */
  under: string;
  /** per token: the pin it belongs to, with o/c marking the pin's first and last token */
  pins: (string | null)[];
  pinEdge: string;
  /** ten cells, each 0-3 */
  cells: string;
  /** the line's attention is in the top tenth */
  top: boolean;
  score: number;
  /** the lock shown beside this line */
  lock: { id: string; weight: number } | null;
  /** this line is being, or would be, regenerated by a control change */
  zone: 'none' | 'steer' | 'live';
  number: number | null;
  sig: string;
}

const TONE: Record<string, string> = { k: 'k', a: 'a', s: 's', g: 'g' };

function Gutter({ view, variant }: { view: RowView; variant: GutterVariant }) {
  const filled = Math.round(view.score * 10);
  return (
    <span className="stc-gut" aria-hidden="true">
      <span className={`stc-zone ${view.zone}`} />
      {variant === 'weight' ? (
        <span className={'stc-weight' + (view.top ? ' top' : '')}>
          <i style={{ width: `${Math.round(view.score * 100)}%` }} />
        </span>
      ) : (
        <span className={'stc-cells' + (view.top ? ' top' : '')}>
          {Array.from({ length: 10 }, (_, i) => (
            <i key={i} className={variant === 'bar' ? (i < filled ? 'l2' : 'l0') : `l${view.cells[i] ?? '0'}`} />
          ))}
        </span>
      )}
      <span className="stc-lock" data-lock={view.lock?.id} title={view.lock ? 'attention lock: drag up or down to change its weight, double-click to release' : undefined}>
        {view.lock ? (
          <>
            <i />
            {view.lock.weight.toFixed(2).replace(/^0/, '')}
          </>
        ) : null}
      </span>
      <span className="stc-no">{view.number ?? ''}</span>
    </span>
  );
}

function RowImpl({ view, variant }: { view: RowView; variant: GutterVariant }) {
  const { row } = view;
  return (
    <div className="stc-row" data-r={view.index}>
      <Gutter view={view} variant={variant} />
      <span className="stc-text">
        {row.shown.map((text, j) => {
          const i = row.start + j;
          if (!text) return null;
          let cls = TONE[view.tone[j]] ?? 's';
          if (view.under[j] === '1') cls += ' u';
          const pin = view.pins[j];
          if (pin) cls += ` p${view.pinEdge[j] === 'o' || view.pinEdge[j] === 'b' ? ' po' : ''}${view.pinEdge[j] === 'c' || view.pinEdge[j] === 'b' ? ' pc' : ''}`;
          // The space in front of a word sits outside its span, so an underline or the
          // start of a pin's box begins at the word. Inside a pin it stays in, so the box is unbroken.
          const inside = pin && view.pinEdge[j] !== 'o' && view.pinEdge[j] !== 'b';
          const gap = inside ? 0 : text.length - text.trimStart().length;
          return (
            <span key={`${i}:${text}`} className="t" data-i={i} data-pin={pin ?? undefined} title={pin ? 'pinned: click to release' : undefined}>
              {gap > 0 && text.slice(0, gap)}
              <span className={cls}>{text.slice(gap)}</span>
            </span>
          );
        })}
      </span>
    </div>
  );
}

export const TextRow = memo(RowImpl, (a, b) => a.view.sig === b.view.sig && a.variant === b.variant);
